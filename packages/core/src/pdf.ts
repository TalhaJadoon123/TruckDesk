/**
 * Try pdfme first. If it is not present in this runtime (a slim Worker bundle,
 * a cold edge isolate) fall back to the built-in writer. The returned
 * `renderer` field says which path ran, and tests assert on it.
 */
export async function render(options: PdfRenderOptions): Promise<RenderedDocument> {
  const pdfme = await loadPdfme().catch(() => null);
  if (pdfme) {
    try {
      const bytes = await renderWithPdfme(pdfme, options);
      return {
        bytes,
        mimeType: 'application/pdf',
        fileName: fileNameFor(options),
        renderer: 'pdfme',
      };
    } catch {
      // Fall through: a pdfme schema mismatch should never fail a POD.
    }
  }

  return {
    bytes: renderBuiltin(options),
    mimeType: 'application/pdf',
    fileName: fileNameFor(options),
    renderer: 'builtin',
  };
}

export function fileNameFor(options: PdfRenderOptions): string {
  const slug = options.title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
  return `${slug}.pdf`;
}

