/**
 * Minimal PDF writer, no dependencies. Produces a valid single-page document
 * using the standard Helvetica fonts that every reader has built in. It exists
 * so that document generation never becomes an outage: no pdfme, no font
 * upload, no template JSON.
 */
export function renderBuiltin(options: PdfRenderOptions): Uint8Array {
  const lines: string[] = [];
  lines.push(`TruckDesk - ${options.title}`);
  if (options.subtitle) lines.push(options.subtitle);
  lines.push('');

  for (const section of options.sections) {
    if (section.title) {
      lines.push(section.title.toUpperCase());
      for (const field of section.fields) {
        lines.push(`  ${field.label}: ${field.value}`);
      }
      lines.push('');
    } else {
      for (const field of section.fields) lines.push(`  ${field.label}: ${field.value}`);
    }
  }

  if (options.table) {
    for (const row of options.table.rows) lines.push(`  ${row.join('  |  ')}`);
    if (options.table.totals) {
      for (const total of options.table.totals) {
        lines.push(`  ${total.label}: ${total.value}`);
      }
    }
    lines.push('');
  }

  if (options.signature) {
    lines.push('');
    lines.push(`  Signature: ${options.signature.name ?? ''}`);
    lines.push(`  Date: ${options.signature.signedAt ?? ''}`);
  }

  if (options.footer) {
    lines.push('');
    lines.push(options.footer);
  }

  // PDF 1.4 text-only document: catalogue, pages, page, font, content stream.
  const content = [
    'BT',
    '/F1 9 Tf',
    `${MARGIN_PT} ${PAGE_HEIGHT_PT - MARGIN_PT} Td`,
    `${leadingFor(lines.length)} TL`,
    ...lines.flatMap((line) => [escapePdfText(line), 'T*']),
    'ET',
  ].join('\n');

  const objects: string[] = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_WIDTH_PT} ${PAGE_HEIGHT_PT}] ` +
      '/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
  ];

  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [];

  objects.forEach((body, index) => {
    offsets.push(pdf.length);
    pdf += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });

  const xrefOffset = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    pdf += `${offset.toString().padStart(10, '0')} 00000 n \n`;
  }
  pdf +=
    `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\n` +
    `startxref\n${xrefOffset}\n%%EOF\n`;

  return new TextEncoder().encode(pdf);
}

function leadingFor(lineCount: number): number {
  // Compress leading when the content would overflow one page.
  return lineCount > 60 ? 9 : lineCount > 44 ? 11 : 13;
}

function escapePdfText(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function windowLabel(window: { start: Iso; end: Iso }): string {
  return `${formatDate(window.start)} - ${formatDate(window.end)}`;
}

/** Stop summary used by the BOL header block. */
export function stopSummary(stops: readonly LoadStop[]): string {
  return stops
    .slice()
    .sort((a, b) => a.sequence - b.sequence)
    .map((stop) => `${stop.sequence}. ${stop.type} ${stop.facilityName}, ${stop.city} ${stop.state}`)
    .join(' | ');
}