export async function renderPod(input: {
  load: Load;
  companyName: string;
  driverName?: string;
  receiverName?: string;
  signatureDataUrl?: string;
  signatureName?: string;
  exceptions?: string[];
  photos?: Array<{ fileName: string; capturedAt?: Iso }>;
}): Promise<RenderedDocument> {
  const { load } = input;
  const stops = (load.stops ?? []).filter((stop) => stop.type === 'delivery');
  const deliveredStop = stops[0];

  return render({
    kind: 'pod',
    title: 'Proof of Delivery',
    subtitle: `${load.broker} · ${load.reference ?? load.id}`,
    sections: [
      {
        title: 'Delivery',
        fields: [
          { label: 'Delivered at', value: formatDateTime(load.deliveredAt) },
          { label: 'Facility', value: deliveredStop?.facilityName ?? load.destination },
          { label: 'Pieces received', value: load.weightLbs ? `${load.weightLbs.toLocaleString()} lbs` : '-' },
          { label: 'Trailer', value: load.equipment ?? 'dry van' },
          { label: 'Driver', value: input.driverName ?? '-' },
          { label: 'Receiver', value: input.receiverName ?? input.signatureName ?? '-' },
        ],
      },
      {
        title: 'Carrier',
        fields: [{ label: 'Carrier', value: input.companyName }],
      },
    ],
    table:
      input.photos && input.photos.length > 0
        ? {
            columns: [
              { label: 'Photo', width: 0.6 },
              { label: 'Captured', width: 0.4, align: 'right' },
            ],
            rows: input.photos.map((photo) => [
              photo.fileName,
              formatDateTime(photo.capturedAt),
            ]),
          }
        : undefined,
    signature: {
      name: input.signatureName ?? input.receiverName,
      signedAt: load.deliveredAt,
    },
    footer: input.exceptions?.length
      ? `EXCEPTIONS: ${input.exceptions.join('; ')}`
      : 'Freight received in good order with no exceptions.',
  });
}

