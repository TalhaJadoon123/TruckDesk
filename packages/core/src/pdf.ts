import { formatDate, formatDateTime, formatUsd, type Cents, type Iso, type Load, type LoadStop } from '@truckdesk/shared';

/**
 * Document generation: rate confirmation, BOL, POD, invoice.
 *
 * Primary renderer is pdfme (MIT). pdfme needs fonts registered per document,
 * and it is loaded dynamically so that a Worker bundle without pdfme simply
 * falls through to the built-in writer below rather than failing at import
 * time. The fallback emits a valid, if plain, PDF with no dependencies at all -
 * so `POST /loads/:id/bol` works in a cold Worker, in Docker, and in tests.
 */

export type DocumentKind = 'rate_con' | 'bol' | 'pod' | 'invoice' | 'settlement';

export interface PdfRenderOptions {
  kind: DocumentKind;
  title: string;
  subtitle?: string;
  /** Left column: label/value pairs. Right column: the same. */
  sections: PdfSection[];
  table?: PdfTable;
  footer?: string;
  /** Signature block, for POD and settlement. */
  signature?: { name?: string; signedAt?: Iso; capturedAt?: Iso };
}

export interface PdfSection {
  title?: string;
  fields: Array<{ label: string; value: string }>;
  /** Render a whole section at normal weight instead of bold. */
  compact?: boolean;
}

export interface PdfTable {
  columns: Array<{ label: string; width: number; align?: 'left' | 'right' | 'center' }>;
  rows: string[][];
  /** Drawn in bold above the totals rows. */
  totals?: Array<{ label: string; value: string }>;
}

export interface RenderedDocument {
  bytes: Uint8Array;
  mimeType: 'application/pdf';
  fileName: string;
  renderer: 'pdfme' | 'builtin';
}

export const PAGE_WIDTH_PT = 612; // US Letter at 72dpi
export const PAGE_HEIGHT_PT = 792;
const MARGIN_PT = 48;

