/* pdfme path                                                                    */
/* -------------------------------------------------------------------------- */

interface PdfmeModule {
  PDFDocument: new (config: unknown) => { addText: (ops: unknown[]) => Promise<unknown>; save: () => Promise<ArrayBuffer> };
  StandardFonts: { Helvetica: string; HelveticaBold: string };
}

let pdfmePromise: Promise<PdfmeModule | null> | null = null;

async function loadPdfme(): Promise<PdfmeModule | null> {
  if (!pdfmePromise) {
    pdfmePromise = (async () => {
      try {
        const moduleName = 'pdfme';
        const imported = (await import(/* @vite-ignore */ moduleName)) as Record<string, unknown>;
        const PDFDocument = imported['PDFDocument'] as PdfmeModule['PDFDocument'] | undefined;
        const StandardFonts = imported['StandardFonts'] as PdfmeModule['StandardFonts'] | undefined;
        if (!PDFDocument || !StandardFonts) return null;
        return { PDFDocument, StandardFonts };
      } catch {
        return null;
      }
    })();
  }
  return pdfmePromise;
}

const FONT_REGULAR = 'Helvetica';
const FONT_BOLD = 'Helvetica-Bold';

async function renderWithPdfme(
  pdfme: PdfmeModule,
  options: PdfRenderOptions,
): Promise<Uint8Array> {
  const doc = new pdfme.PDFDocument({
    pdfVersion: '1.7',
    pageSize: { width: PAGE_WIDTH_PT, height: PAGE_HEIGHT_PT },
    margins: { top: MARGIN_PT, bottom: MARGIN_PT, left: MARGIN_PT, right: MARGIN_PT },
    fonts: {
      [FONT_REGULAR]: { data: '', fontName: FONT_REGULAR },
      [FONT_BOLD]: { data: '', fontName: FONT_BOLD },
    },
  });

  const ops = layoutToPdfmeOps(options, pdfme.StandardFonts);
  await doc.addText(ops);
  const buffer = await doc.save();
  return new Uint8Array(buffer);
}

/** Convert the layout model into pdfme text/rect draw operations. */
function layoutToPdfmeOps(options: PdfRenderOptions, fonts: PdfmeModule['StandardFonts']): unknown[] {
  const ops: unknown[] = [];
  const contentWidth = PAGE_WIDTH_PT - MARGIN_PT * 2;
  let y = MARGIN_PT;

  const text = (
    value: string,
    x: number,
    yPos: number,
    width: number,
    size: number,
    fontName: string,
    align: 'left' | 'center' | 'right' = 'left',
  ) => {
    ops.push({
      text: value.slice(0, Math.max(8, Math.floor(width / (size * 0.5)))),
      x,
      y: yPos,
      width,
      fontSize: size,
      fontName,
      color: '#111111',
      ...(align === 'center' ? { alignment: 'center' } : {}),
      ...(align === 'right' ? { alignment: 'right' } : {}),
    });
  };

  const rect = (x: number, yPos: number, width: number, height: number, color: string) => {
    ops.push({
      rectangle: { x, y: yPos, width, height },
      color,
      borderWidth: 0,
    });
  };

  /* header */
  text(options.title, MARGIN_PT, y, contentWidth, 20, fonts.HelveticaBold);
  y += 26;
  if (options.subtitle) {
    text(options.subtitle, MARGIN_PT, y, contentWidth, 10, fonts.Helvetica);
    y += 16;
  }
  rect(MARGIN_PT, y, contentWidth, 1, '#d4d4d8');
  y += 18;

  /* sections, two columns */
  const columnWidth = (contentWidth - 24) / 2;
  const sectionRows = Math.max(
    1,
    ...options.sections.map((section) => section.fields.length + (section.title ? 2 : 0)),
  );

  for (let index = 0; index < options.sections.length; index += 1) {
    const section = options.sections[index];
    if (!section) continue;
    const column = index % 2;
    const row = Math.floor(index / 2);
    const x = MARGIN_PT + column * (columnWidth + 24);
    const startY = y + row * (sectionRows * 16 + 16);

    let localY = startY;
    if (section.title) {
      text(section.title.toUpperCase(), x, localY, columnWidth, 8, fonts.HelveticaBold);
      localY += 14;
    }
    for (const field of section.fields) {
      text(field.label, x, localY, columnWidth * 0.42, 8, fonts.Helvetica);
      text(field.value, x + columnWidth * 0.42, localY, columnWidth * 0.58, 8, fonts.HelveticaBold);
      localY += 13;
    }
  }

  y += sectionRows * 16 + 28;

  /* table */
  if (options.table) {
    const widths = options.table.columns.map((column) => column.width * contentWidth);
    let x = MARGIN_PT;

    options.table.columns.forEach((column, index) => {
      const width = widths[index] ?? 0;
      const align = column.align ?? 'left';
      text(
        column.label.toUpperCase(),
        align === 'right' ? x + width - 80 : x,
        y,
        Math.min(width, 80),
        8,
        fonts.HelveticaBold,
        align,
      );
      x += width;
    });
    y += 6;
    rect(MARGIN_PT, y, contentWidth, 0.75, '#a1a1aa');
    y += 12;

    for (const row of options.table.rows) {
      let cellX = MARGIN_PT;
      row.forEach((cell, index) => {
        const width = widths[index] ?? 0;
        const align = options.table?.columns[index]?.align ?? 'left';
        text(String(cell), align === 'right' ? cellX + width - 90 : cellX, y, Math.min(width, 90), 8, fonts.Helvetica, align);
        cellX += width;
      });
      y += 13;
    }

    if (options.table.totals && options.table.totals.length > 0) {
      y += 8;
      rect(MARGIN_PT, y, contentWidth, 0.75, '#a1a1aa');
      y += 12;
      for (const total of options.table.totals) {
        text(total.label, MARGIN_PT + contentWidth - 260, y, 160, 8, fonts.Helvetica);
        text(total.value, MARGIN_PT + contentWidth - 100, y, 100, 8, fonts.HelveticaBold, 'right');
        y += 13;
      }
    }
  }

  /* signature */
  if (options.signature) {
    y = Math.max(y + 32, PAGE_HEIGHT_PT - 220);
    rect(MARGIN_PT, y, 260, 0.75, '#3f3f46');
    text(
      `Signature: ${options.signature.name ?? '________________'}`,
      MARGIN_PT,
      y + 8,
      260,
      8,
      fonts.Helvetica,
    );
    text(`Date: ${formatDateTime(options.signature.signedAt)}`, MARGIN_PT, y + 22, 260, 8, fonts.Helvetica);
  }

  /* footer */
  if (options.footer) {
    text(
      options.footer,
      MARGIN_PT,
      PAGE_HEIGHT_PT - MARGIN_PT,
      contentWidth,
      8,
      fonts.Helvetica,
    );
  }

  return ops;
}

